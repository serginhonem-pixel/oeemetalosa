export const CATALOGO_PARA_SANKHYA = Object.fromEntries(
  Object.entries(SANKHYA_PARA_CATALOGO).map(([sankhya, catalogo]) => [catalogo, sankhya])
);

// Converte um código vindo do Sankhya/Access para o código do catálogo.
// Códigos que não estão no de-para (ou que já são do catálogo) voltam iguais.
export const codCatalogo = (cod) => {
  const key = String(cod ?? '').trim();
  return SANKHYA_PARA_CATALOGO[key] || key;
};

// Código Sankhya de um item do catálogo (ou '' se não houver).
export const codSankhya = (codCatalogoItem) =>
  CATALOGO_PARA_SANKHYA[String(codCatalogoItem ?? '').trim()] || '';
